const assert=require('node:assert/strict');
const {buildFunnel}=require('../walkflows/research_funnel.js');
const zones=[{id:'a',name:'A',type:'zone',x1:0,y1:0,x2:1,y2:2},{id:'b',name:'B',type:'zone',x1:1,y1:0,x2:2,y2:2},{id:'c',name:'C',type:'zone',x1:2,y1:0,x2:3,y2:2}];
const p=(f,x)=>({frame:f,x,y:1,status:'research_candidate'}),opt={margin:0,minDuration:0,maxInterval:1.1,fps:1,window_s:10};
const tracks=[{id:'complete',samples:[p(0,.5),p(1,1.5),p(2,2.5)]},{id:'gap',samples:[p(0,.5),p(1,1.5),p(3,2.5)]}];
let result=buildFunnel(tracks,zones,['a','b','c'],opt);
assert.deepEqual(result.steps.map(s=>s.hypotheses),[2,2,1]);
assert.deepEqual(result.tracks.map(t=>t.reached),[3,2]);
assert.equal(result.tracks[1].gaps,1);
const overlap=[{...zones[0],id:'a'}, {...zones[0],id:'b'}];
result=buildFunnel([{id:'same-frame',samples:[p(0,.5),p(1,.5)]}],overlap,['a','b'],opt);
assert.deepEqual(result.steps.map(s=>s.hypotheses),[1,0]);
assert.throws(()=>buildFunnel(tracks,zones,['a','a'],opt));
assert.throws(()=>buildFunnel(tracks,zones,['a','missing'],opt));
assert.throws(()=>buildFunnel([tracks[0],tracks[0]],zones,['a','b'],opt));
const repeat={id:'repeat',samples:[p(0,.5),p(1,3.5),p(2,.5),p(3,1.5)]};
let timed=buildFunnel([repeat],zones,['a','b'],{...opt,window_s:1.5});
assert.equal(timed.tracks[0].reached,2);
assert.deepEqual(timed.tracks[0].evidence.map(e=>e.frame),[2,3]);
assert.throws(()=>buildFunnel(tracks,zones,['a','b'],{...opt,window_s:0}));
const expired={id:'expired',samples:[p(0,.5),p(4,1.5)]};
const expiredResult=buildFunnel([expired],zones,['a','b'],{...opt,window_s:2});
assert.equal(expiredResult.tracks[0].interruptions,0);
assert.equal(expiredResult.tracks[0].reached,1);
const resumed={id:'later',samples:[p(0,.5),p(1,1.5),p(4,.5),p(5,1.5),p(6,2.5)]};
const resumedResult=buildFunnel([resumed],zones,['a','b','c'],opt);
assert.equal(resumedResult.tracks[0].reached,3);
assert.equal(resumedResult.tracks[0].interruptions,1);
assert.deepEqual(resumedResult.tracks[0].evidence.map(e=>e.frame),[4,5,6]);
assert.throws(()=>buildFunnel([],zones,['a','b'],{...opt,margin:-1}));
assert.throws(()=>buildFunnel([],[{...zones[0],x2:0},zones[1]],['a','b'],opt));
console.log('research funnel tests passed');
