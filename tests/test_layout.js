const assert = require('node:assert/strict');
const {emptyLayout, validateLayout, saveItem, removeItem, migrateLegacy} = require('../walkflows/layout.js');
const bounds=[-2,-3,4,5], scene='site02-v1';
const a={id:'a',name:'Entrance',type:'zone',x1:-1,y1:-2,x2:0,y2:0};
const b={id:'b',name:'Display',type:'point',x1:1,y1:1,x2:2,y2:2};
let layout=emptyLayout(scene);
layout=saveItem(layout,a,bounds,scene);
layout=saveItem(layout,b,bounds,scene);
assert.equal(layout.revision,3);
assert.equal(layout.items.length,2);
assert.deepEqual(validateLayout(JSON.parse(JSON.stringify(layout)),bounds,scene),layout);
assert.equal(saveItem(layout,{...a,name:'Door'},bounds,scene).items[0].name,'Door');
assert.equal(removeItem(layout,'a',bounds,scene).items.length,1);
assert.equal(layout.items.length,2);
assert.throws(()=>validateLayout({...layout,scene:'other'},bounds,scene));
assert.throws(()=>validateLayout({...layout,items:[a,a]},bounds,scene));
assert.throws(()=>saveItem(layout,{...a,x1:NaN},bounds,scene));
assert.throws(()=>saveItem(layout,{...a,type:'invalid'},bounds,scene));
assert.throws(()=>saveItem(layout,{...a,x1:-4},bounds,scene));
assert.throws(()=>removeItem(layout,'missing',bounds,scene));
const migrated=migrateLegacy({name:'Old',x1:0,y1:0,x2:1,y2:1},bounds,scene);
assert.equal(migrated.items[0].name,'Old');
assert.equal(migrated.items[0].type,'zone');
assert.equal(migrated.revision,1);
const {exampleGrid}=require('../walkflows/layout.js');
const example=exampleGrid('scene',[-6,-3,3,10]);
assert.equal(example.items.length,4);
assert.deepEqual(example.items.map(x=>[x.x1,x.y1,x.x2,x.y2]),[[-6,-3,-1.5,3.5],[-1.5,-3,3,3.5],[-6,3.5,-1.5,10],[-1.5,3.5,3,10]]);
assert.throws(()=>exampleGrid('scene',[0,0,0,1]));
console.log('layout tests passed');
