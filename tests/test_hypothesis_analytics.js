const assert=require('node:assert/strict');
const {zoneEvents,heatmap,movementDirection}=require('../walkflows/hypothesis_analytics.js');
const sample=(frame,x,y=1,status='research_candidate')=>({frame,x:status==='spatial_conflict'?null:x,y:status==='spatial_conflict'?null:y,status});
const h={id:'a',samples:[sample(0,.2),sample(1,.3),sample(2,1.2),sample(3,0,0,'spatial_conflict'),sample(4,1.3),sample(5,1.4)]};
const grid=heatmap([h],[0,0,2,2],{columns:2,rows:1,fps:2});
assert.deepEqual(grid.samples,[[2,3]]);
assert.deepEqual(grid.crossings,[[0,1]]);
assert.deepEqual(grid.seconds,[[.5,.5]]);
assert.deepEqual(grid.starts,[[1,1]]);
const z={x1:0,y1:0,x2:1,y2:2};
const result=zoneEvents(h,z,{margin:0,minDuration:0,maxInterval:.6,fps:2});
assert.deepEqual(result.events.map(x=>x.kind),['initial_inside','exit_candidate','gap']);
assert.throws(()=>heatmap([h,h],[0,0,2,2],{columns:2,rows:1,fps:2}));
assert.throws(()=>heatmap([{id:'b',samples:[sample(0,3)]}],[0,0,2,2],{columns:2,rows:1,fps:2}));
const repeated={id:'r',samples:[sample(0,.2),sample(1,1.2),sample(2,.2)]};
assert.deepEqual(heatmap([repeated],[0,0,2,2],{columns:2,rows:1,fps:2}).visitors,[[1,1]]);
const {createResearchReport}=require('../walkflows/hypothesis_analytics.js');
const data={scene:'scene',bounds:[0,0,2,2],fps:2,hypotheses:[h],research_metadata:{hypothesis_sha256:'a'.repeat(64)}};
const layout={schema_version:1,scene:'scene',revision:2,items:[{id:'z',name:'Zone',type:'zone',x1:0,y1:0,x2:1,y2:2}]};
const report=createResearchReport(data,layout,{margin:0,minDuration:0,maxInterval:.6,columns:2,rows:1});
assert.equal(report.source.hypothesis_sha256,'a'.repeat(64));
assert.equal(report.areas[0].hypotheses[0].selected,5);
assert.equal(report.heatmaps.visitors[0][0],1);
layout.items[0].name='changed';assert.equal(report.layout.items[0].name,'Zone');
assert.throws(()=>createResearchReport(data,{...layout,scene:'other'},{margin:0,minDuration:0,maxInterval:.6,columns:2,rows:1}));
assert.equal(zoneEvents(h,z,{margin:0,minDuration:0,maxInterval:.6,fps:2}).observed_inside_seconds,.5);
const {summarizeArea}=require('../walkflows/hypothesis_analytics.js');
const areaSummary=summarizeArea([h],z,{margin:0,minDuration:0,maxInterval:.6,fps:2});
assert.equal(areaSummary.observed_hypotheses,1);
assert.equal(areaSummary.candidate_enter_events,0);
assert.equal(areaSummary.initial_or_resumed_inside,1);
assert.equal(areaSummary.observed_inside_seconds,.5);
const delayed={id:'delay',samples:[sample(0,.2),sample(1,.2),sample(2,.2),sample(3,.2)]};
assert.equal(zoneEvents(delayed,z,{margin:0,minDuration:1,maxInterval:.6,fps:2}).observed_inside_seconds,.5);
const {researchRoute}=require('../walkflows/hypothesis_analytics.js');
const zones=[{id:'a',name:'A',type:'zone',x1:0,y1:0,x2:1,y2:2},{id:'b',name:'B',type:'point',x1:0,y1:0,x2:1,y2:2}];
const route=researchRoute(h,zones,{margin:0,minDuration:0,maxInterval:.6,fps:2});
assert.deepEqual(route.map(x=>[x.kind,x.frame,x.items.length]),[['candidates',0,2],['candidates',2,2],['gap',4,0]]);
assert.throws(()=>researchRoute(h,[zones[0],zones[0]],{margin:0,minDuration:0,maxInterval:.6,fps:2}));
console.log('hypothesis analytics tests passed');

// Movement direction is derived only from contiguous valid samples.
const movementTrack={id:'motion',samples:Array.from({length:6},(_,frame)=>({frame,status:'research_candidate',x:frame*.1,y:0}))};
assert.deepEqual(movementDirection(movementTrack,5,{intervals:5,minDisplacement:.1}),{start_frame:0,end_frame:5,dx:.5,dy:0,distance:.5,unit_x:1,unit_y:0});
assert.equal(movementDirection(movementTrack,4,{intervals:5,minDisplacement:.1}),null);
assert.equal(movementDirection({...movementTrack,samples:movementTrack.samples.filter(s=>s.frame!==3)},5,{intervals:5,minDisplacement:.1}),null);
assert.equal(movementDirection({...movementTrack,samples:movementTrack.samples.map(s=>({...s,x:0}))},5,{intervals:5,minDisplacement:.1}),null);
assert.equal(movementDirection({...movementTrack,samples:movementTrack.samples.map(s=>s.frame===3?{...s,status:'spatial_conflict',x:null,y:null}:s)},5,{intervals:5,minDisplacement:.1}),null);

